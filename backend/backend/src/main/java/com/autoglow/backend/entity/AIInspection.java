package com.autoglow.backend.entity;

import jakarta.persistence.*;
import java.time.LocalDateTime;

@Entity
@Table(name = "ai_inspections", indexes = {
        @Index(name = "idx_ai_inspection_vehicle_number", columnList = "vehicle_number"),
        @Index(name = "idx_ai_inspection_status", columnList = "status"),
        @Index(name = "idx_ai_inspection_created_at", columnList = "created_at")
})
public class AIInspection {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /*
     * Vehicle registration number.
     * Example:
     * DL 01 AB 4587
     */
    @Column(name = "vehicle_number", nullable = false, length = 30)
    private String vehicleNumber;

    /*
     * Vehicle type.
     * Example:
     * Car, SUV, Bike, Sedan etc.
     */
    @Column(name = "vehicle_type", length = 30)
    private String vehicleType;

    /*
     * Uploaded vehicle image URL/path.
     *
     * Example:
     * /uploads/ai-inspection/uuid.jpg
     */
    @Column(name = "image_url", nullable = false, length = 500)
    private String imageUrl;

    /*
     * AI generated overall health score.
     *
     * Range:
     * 0 - 100
     */
    @Column(name = "overall_score")
    private Integer overallScore;

    /*
     * Total number of detected issues.
     */
    @Column(name = "finding_count")
    private Integer findingCount = 0;

    /*
     * Number of HIGH severity findings.
     */
    @Column(name = "high_severity_count")
    private Integer highSeverityCount = 0;

    /*
     * Average AI confidence.
     *
     * Example:
     * 91.5
     */
    @Column(name = "average_confidence")
    private Double averageConfidence;

    /*
     * Inspection status.
     *
     * Possible values:
     *
     * PENDING
     * PROCESSING
     * COMPLETED
     * FAILED
     */
    @Column(name = "status", nullable = false, length = 20)
    private String status;

    /*
     * General AI summary.
     */
    @Column(name = "summary", length = 2000)
    private String summary;

    /*
     * Recommended services generated by AI.
     *
     * We are keeping this as text for now.
     * Later we can create a separate
     * AIInspectionRecommendation entity if required.
     */
    @Column(name = "recommendations", length = 5000)
    private String recommendations;

    /*
     * Error message if AI processing fails.
     */
    @Column(name = "error_message", length = 2000)
    private String errorMessage;

    /*
     * Record creation time.
     */
    @Column(name = "created_at", nullable = false)
    private LocalDateTime createdAt;

    /*
     * Last update time.
     */
    @Column(name = "updated_at")
    private LocalDateTime updatedAt;

    // =========================================================
    // CONSTRUCTORS
    // =========================================================

    public AIInspection() {
    }

    // =========================================================
    // PRE PERSIST
    // =========================================================

    @PrePersist
    public void onCreate() {

        LocalDateTime now = LocalDateTime.now();

        if (createdAt == null) {
            createdAt = now;
        }

        updatedAt = now;

        if (status == null || status.isBlank()) {
            status = "PENDING";
        }

        if (findingCount == null) {
            findingCount = 0;
        }

        if (highSeverityCount == null) {
            highSeverityCount = 0;
        }
    }

    // =========================================================
    // PRE UPDATE
    // =========================================================

    @PreUpdate
    public void onUpdate() {
        updatedAt = LocalDateTime.now();
    }

    // =========================================================
    // GETTERS & SETTERS
    // =========================================================

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public String getVehicleNumber() {
        return vehicleNumber;
    }

    public void setVehicleNumber(String vehicleNumber) {
        this.vehicleNumber = vehicleNumber;
    }

    public String getVehicleType() {
        return vehicleType;
    }

    public void setVehicleType(String vehicleType) {
        this.vehicleType = vehicleType;
    }

    public String getImageUrl() {
        return imageUrl;
    }

    public void setImageUrl(String imageUrl) {
        this.imageUrl = imageUrl;
    }

    public Integer getOverallScore() {
        return overallScore;
    }

    public void setOverallScore(Integer overallScore) {
        this.overallScore = overallScore;
    }

    public Integer getFindingCount() {
        return findingCount;
    }

    public void setFindingCount(Integer findingCount) {
        this.findingCount = findingCount;
    }

    public Integer getHighSeverityCount() {
        return highSeverityCount;
    }

    public void setHighSeverityCount(Integer highSeverityCount) {
        this.highSeverityCount = highSeverityCount;
    }

    public Double getAverageConfidence() {
        return averageConfidence;
    }

    public void setAverageConfidence(Double averageConfidence) {
        this.averageConfidence = averageConfidence;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public String getSummary() {
        return summary;
    }

    public void setSummary(String summary) {
        this.summary = summary;
    }

    public String getRecommendations() {
        return recommendations;
    }

    public void setRecommendations(String recommendations) {
        this.recommendations = recommendations;
    }

    public String getErrorMessage() {
        return errorMessage;
    }

    public void setErrorMessage(String errorMessage) {
        this.errorMessage = errorMessage;
    }

    public LocalDateTime getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(LocalDateTime createdAt) {
        this.createdAt = createdAt;
    }

    public LocalDateTime getUpdatedAt() {
        return updatedAt;
    }

    public void setUpdatedAt(LocalDateTime updatedAt) {
        this.updatedAt = updatedAt;
    }
}